#!/usr/bin/env python3
"""Extract the real upstream kernels without importing cocotb."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def workloads():
    result = []
    for name in ("matadd", "matmul"):
        tree = ast.parse((ROOT / "test" / f"test_{name}.py").read_text())
        values = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id in ("program", "data", "threads"):
                        values[target.id] = ast.literal_eval(node.value)
        data = values["data"]
        if name == "matadd":
            expected = [(a + b) & 255 for a, b in zip(data[:8], data[8:16])]
            base = 16
        else:
            expected = [sum(data[r*2+k] * data[4+k*2+c] for k in range(2)) & 255
                        for r in range(2) for c in range(2)]
            base = 8
        result.append(dict(name=name, **values, result_base=base, expected=expected))
    return result


def outputs():
    kernels = workloads()
    lines = ["// Generated by fpga/tools/gen_workloads.py from test/test_mat*.py."]
    fields = [("program", 16, "program", 0xf000), ("data", 8, "data", 0),
              ("expected", 8, "expected", 0)]
    for name, width, key, default in fields:
        lines += [f"function [{width-1}:0] demo_{name};", "    input kernel;",
                  "    input [7:0] index;", "    begin", "        case ({kernel, index})"]
        for kernel, item in enumerate(kernels):
            for index, value in enumerate(item[key]):
                lines.append(f"            9'd{kernel*256+index}: demo_{name} = {width}'h{value:0{width//4}x};")
        lines += [f"            default: demo_{name} = {width}'h{default:0{width//4}x};",
                  "        endcase", "    end", "endfunction"]
    for name, key in (("threads", "threads"), ("result_base", "result_base"), ("result_count", "expected")):
        vals = [len(k[key]) if isinstance(k[key], list) else k[key] for k in kernels]
        lines += [f"function [7:0] demo_{name};", "    input kernel;", "    begin",
                  f"        demo_{name} = kernel ? 8'd{vals[1]} : 8'd{vals[0]};", "    end", "endfunction"]
    return {ROOT / "fpga/generated/workloads.vh": "\n".join(lines) + "\n",
            ROOT / "fpga/generated/workloads.json": json.dumps(kernels, indent=2) + "\n"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Stale generated workload: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("PASS: upstream workload images " + ("checked" if args.check else "generated"))
